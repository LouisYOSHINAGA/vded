/** Best guess from the browser, used only for the very first run. */
export function detectLang(): Lang {
  if (typeof navigator === 'undefined') return 'en'
  return navigator.languages?.some((l) => l.toLowerCase().startsWith('ja')) ? 'ja' : 'en'
}

